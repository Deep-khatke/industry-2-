"""Phase 11: Cryptographic Dual-Signature & Release Manifest Tests."""

import json
from pathlib import Path
import pytest

from fcs_governance.contracts.manifest import CanonicalManifestBody
from fcs_governance.crypto.dual_signer import DualSignatureVerificationError, DualSigner

ROOT_DIR = Path(__file__).resolve().parents[3]


def test_dual_signature_generation_and_verification():
    """Verify dual ECDSA P-256 and ML-DSA-65 post-quantum signing and verification."""
    signer, keys = DualSigner.create_ephemeral_dev_signer()

    body = CanonicalManifestBody(
        release_id="rel-phase11-test",
        schema_version="1.2.0",
        manifest_sequence=11,
        artifact_digest_sha384="a" * 96,
        feature_schema_digest="b" * 64,
        model_lineage_reference="parent-candidate-01",
        evaluation_reference="eval-report-hash-123",
        validity_interval_start="2026-01-01T00:00:00Z",
        validity_interval_end="2099-01-01T00:00:00Z",
    )

    manifest = signer.sign_manifest(body)

    # Valid verification
    assert DualSigner.verify_manifest(
        manifest,
        expected_artifact_digest="a" * 96,
        trusted_ecdsa_key_hex=keys["ecdsa_public_key_hex"],
        trusted_mldsa_key_hex=keys["mldsa_public_key_hex"],
    ) is True

    # Tampered digest rejection
    with pytest.raises(DualSignatureVerificationError, match="Artifact digest mismatch"):
        DualSigner.verify_manifest(
            manifest,
            expected_artifact_digest="c" * 96,
            trusted_ecdsa_key_hex=keys["ecdsa_public_key_hex"],
            trusted_mldsa_key_hex=keys["mldsa_public_key_hex"],
        )


def test_phase11_disk_release_manifest_validity():
    """Verify that the generated Phase 11 release manifest exists and is dual-signed."""
    manifest_path = ROOT_DIR / "artifacts" / "phase11" / "release-manifests" / "phase11_release_manifest.json"
    assert manifest_path.exists(), "Release manifest must be pre-generated by build_release_manifest.py"

    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert data["body"]["schema_version"] == "1.2.0"
    assert data["body"]["manifest_sequence"] == 11
    assert "conventional_signature" in data
    assert "post_quantum_signature" in data
    assert data["conventional_signature"]["algorithm"] == "ECDSA_P256_SHA384"
    assert data["post_quantum_signature"]["algorithm"] == "ML_DSA_65"
